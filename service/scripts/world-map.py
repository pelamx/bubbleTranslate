"""Writes src/admin/world.ts: the admin panel's dotted world map.

The panel draws the map itself rather than fetching one, so it needs the land
as a grid of dots and a point to put each country's dot on. Both come from
Natural Earth (public domain), downloaded once:

  curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
  curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
  python3 -I scripts/world-map.py ne_110m_land.geojson ne_50m_admin_0_countries.geojson > src/admin/world.ts
"""

import json
import sys

STEP = 2.5  # degrees between dots
NORTH, SOUTH = 80.0, -57.5  # Antarctica and the far Arctic are left off


def inside(x, y, ring):
    hit = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]
        xj, yj = ring[j][0], ring[j][1]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def polygons(geometry):
    if geometry["type"] == "Polygon":
        return [geometry["coordinates"]]
    return geometry["coordinates"]


def main(land_path, countries_path):
    land = [p for f in json.load(open(land_path))["features"] for p in polygons(f["geometry"])]

    def on_land(x, y):
        return any(inside(x, y, p[0]) and not any(inside(x, y, h) for h in p[1:]) for p in land)

    cols = int(360 / STEP)
    rows = []
    lat = NORTH
    while lat >= SOUTH:
        bits = "".join("1" if on_land(-180 + STEP / 2 + c * STEP, lat) else "0" for c in range(cols))
        rows.append("%0*x" % (cols // 4, int(bits, 2)))
        lat -= STEP

    points = {}
    for f in json.load(open(countries_path))["features"]:
        p = f["properties"]
        code = p.get("ISO_A2_EH") if p.get("ISO_A2") in (None, "-99") else p.get("ISO_A2")
        if code and code != "-99" and len(code) == 2:
            points[code] = (round(p["LABEL_X"], 1), round(p["LABEL_Y"], 1))

    out = sys.stdout
    out.write("// Generated by scripts/world-map.py from Natural Earth (public domain). Do not edit.\n\n")
    out.write(f"/** Degrees between dots, and the latitude of the first row. */\n")
    out.write(f"export const MAP_STEP = {STEP};\nexport const MAP_NORTH = {NORTH};\n\n")
    out.write("/** One hex string per row of dots, north to south, west to east; a set bit is land. */\n")
    out.write("export const LAND_ROWS = [\n")
    for r in rows:
        out.write(f'  "{r}",\n')
    out.write("];\n\n")
    out.write("/** Where each country's dot goes: [longitude, latitude] of its label point. */\n")
    out.write("export const COUNTRY_POINTS: Record<string, [number, number]> = {\n")
    items = sorted(points.items())
    for i in range(0, len(items), 6):
        out.write("  " + " ".join(f"{k}: [{x}, {y}]," for k, (x, y) in items[i : i + 6]) + "\n")
    out.write("};\n")


main(sys.argv[1], sys.argv[2])
